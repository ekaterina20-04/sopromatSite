declare global {
  interface Window {
    MathJax?: {
      typesetPromise?: (elements?: HTMLElement[]) => Promise<void>;
    };
  }
}

export default function TheoryPage() {
  const navigate = useNavigate();
  const location = useLocation();

  useEffect(() => {
    // Запускаем MathJax typeset после рендера
    if (window.MathJax?.typesetPromise) {
      window.MathJax.typesetPromise().catch(console.error);
    }
  });

  useEffect(() => {
    if (!location.hash) return;
    const id = location.hash.slice(1);
    const scrollToEl = () => {
      const el = document.getElementById(id);
      if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' });
    };
    const timer = setTimeout(scrollToEl, 100);
    return () => clearTimeout(timer);
  }, [location.hash]);

  function tryInCalculator(sectionId: string) {
    navigate(`/calculator?section=${sectionId}`);
  }

  return (
    <div className={styles.page}>
      <h1 className={styles.pageTitle}>Теория сопротивления материалов</h1>
      <p className={styles.pageSubtitle}>
        Справочник по расчёту балок и рам. Формулы, физический смысл и практические примеры.
      </p>

      <nav className={styles.toc}>
        {SECTIONS.map((s) => (
          <a key={s.id} href={`#${s.id}`} className={styles.tocLink}>
            {s.title}
          </a>
        ))}
      </nav>

      <div className={styles.sections}>
        {SECTIONS.map((section) => (
          <article key={section.id} id={section.id} className={styles.section}>
            <h2 className={styles.sectionTitle}>{section.title}</h2>
            <div className={styles.content}>
              {section.content.split('\n\n').map((para, i) => (
                <p key={i} className={styles.para} dangerouslySetInnerHTML={{
                  __html: para
                    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
                    .replace(/\n/g, '<br />')
                }} />
              ))}
            </div>

            {section.formulas && (
              <div className={styles.formulas}>
                {section.formulas.map((f, i) => (
                  <div key={i} className={styles.formula}>
                    {'\\[' + f + '\\]'}
                  </div>
                ))}
              </div>
            )}

            <button
              className={styles.tryBtn}
              onClick={() => tryInCalculator(section.id)}
              type="button"
            >
              Попробовать в калькуляторе →
            </button>
          </article>
        ))}
      </div>
    </div>
  );
}
